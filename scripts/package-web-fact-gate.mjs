#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'web/src/lib/canonical-fact-gate');
const FILES = {
  'verify-cv-facts.mjs': 'verify-cv-facts.mjs',
  'lib/is-main-module.mjs': 'lib/is-main-module.mjs',
  'path-resolver.mjs': 'path-resolver.mjs',
};
mkdirSync(OUTPUT, { recursive: true });
const manifest = { source: 'Generated by scripts/package-web-fact-gate.mjs; do not edit.', files: {} };
for (const [source, filename] of Object.entries(FILES)) {
  const sourcePath = path.join(ROOT, source);
  const outputPath = path.join(OUTPUT, filename);
  mkdirSync(path.dirname(outputPath), { recursive: true });
  copyFileSync(sourcePath, outputPath);
  manifest.files[source] = {
    path: filename,
    sha256: createHash('sha256').update(readFileSync(outputPath)).digest('hex'),
  };
}
writeFileSync(path.join(OUTPUT, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
